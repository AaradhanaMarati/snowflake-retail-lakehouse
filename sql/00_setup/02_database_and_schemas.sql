/* =============================================================================
   02_database_and_schemas.sql
   Medallion layout inside one database:
     RAW      (bronze) - data exactly as landed, plus load metadata
     STAGING  (silver) - typed, deduplicated, conformed
     MARTS    (gold)   - star schema for analytics
     DQ       - data quality results
   ========================================================================== */

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS RETAIL_DB
  DATA_RETENTION_TIME_IN_DAYS = 7
  COMMENT = 'Retail lakehouse - medallion architecture';

CREATE SCHEMA IF NOT EXISTS RETAIL_DB.RAW     WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.STAGING WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.MARTS   WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.DQ      WITH MANAGED ACCESS;

-- Loader: write RAW only
GRANT USAGE ON DATABASE RETAIL_DB TO ROLE RETAIL_LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE PIPE, CREATE FILE FORMAT
  ON SCHEMA RETAIL_DB.RAW TO ROLE RETAIL_LOADER;
GRANT INSERT, SELECT ON FUTURE TABLES IN SCHEMA RETAIL_DB.RAW TO ROLE RETAIL_LOADER;

-- Transformer: read RAW, own STAGING / MARTS / DQ
GRANT USAGE ON DATABASE RETAIL_DB TO ROLE RETAIL_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STREAM, CREATE TASK, CREATE PROCEDURE
  ON SCHEMA RETAIL_DB.STAGING TO ROLE RETAIL_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE DYNAMIC TABLE
  ON SCHEMA RETAIL_DB.MARTS   TO ROLE RETAIL_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE
  ON SCHEMA RETAIL_DB.DQ      TO ROLE RETAIL_TRANSFORMER;

USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE RETAIL_TRANSFORMER;
USE ROLE SYSADMIN;

-- Analyst: read MARTS only
GRANT USAGE ON DATABASE RETAIL_DB TO ROLE RETAIL_ANALYST;
GRANT USAGE ON SCHEMA RETAIL_DB.MARTS TO ROLE RETAIL_ANALYST;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA RETAIL_DB.MARTS TO ROLE RETAIL_ANALYST;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA RETAIL_DB.MARTS TO ROLE RETAIL_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA RETAIL_DB.MARTS TO ROLE RETAIL_ANALYST;
