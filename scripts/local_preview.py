"""
Local preview of the pipeline using DuckDB - no Snowflake account required.

Mirrors the STAGING cleansing rules (dedupe, invalid-quantity filter, casing)
and the MARTS logic (SCD2 point-in-time customer join, daily aggregates),
then writes a Markdown report to docs/sample_output.md so reviewers can see
the gold-layer output directly on GitHub.

Usage:
    pip install duckdb
    python scripts/local_preview.py
"""
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "sample_output.md"


def md_table(con, sql: str) -> str:
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description]
    rows = cur.fetchall()
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    return "\n".join(lines)


def build(con):
    con.sql(f"""
    CREATE OR REPLACE TABLE stg_order_items AS
    SELECT DISTINCT ON (order_line_id)
           order_line_id, order_id, product_id, quantity, unit_price, discount_pct,
           ROUND(quantity * unit_price, 2)                      AS gross_amount,
           ROUND(quantity * unit_price * (1 - discount_pct), 2) AS net_amount,
           quantity > 0 AND unit_price >= 0                     AS is_valid
    FROM read_csv_auto('{RAW}/order_items.csv')
    """)
    con.sql(f"""
    CREATE OR REPLACE TABLE stg_orders AS
    SELECT order_id, customer_id, CAST(order_ts AS TIMESTAMP) AS order_ts,
           CAST(order_ts AS DATE) AS order_date, upper(channel) AS channel,
           upper(status) AS status, upper(ship_country) AS ship_country
    FROM read_csv_auto('{RAW}/orders.csv')
    """)
    con.sql(f"""
    CREATE OR REPLACE TABLE stg_customers AS
    SELECT customer_id, first_name, last_name, lower(nullif(email, '')) AS email,
           upper(country_code) AS country_code, upper(segment) AS segment,
           CAST(updated_at AS TIMESTAMP) AS updated_at,
           md5(concat_ws('|', first_name, last_name, coalesce(lower(email), ''),
                         upper(country_code), upper(segment))) AS record_hash
    FROM read_csv_auto('{RAW}/customers_*.csv', union_by_name = true)
    """)
    con.sql(f"""
    CREATE OR REPLACE TABLE dim_product AS
    SELECT row_number() OVER (ORDER BY product_id) AS product_key, *
    FROM read_csv_auto('{RAW}/products.csv')
    """)
    # SCD2 - identical logic to SP_LOAD_DIM_CUSTOMER
    con.sql("""
    CREATE OR REPLACE TABLE dim_customer AS
    WITH changes AS (
      SELECT *, lag(record_hash) OVER (PARTITION BY customer_id ORDER BY updated_at) AS prev_hash
      FROM stg_customers
    ), versions AS (
      SELECT * FROM changes WHERE prev_hash IS NULL OR prev_hash <> record_hash
    )
    SELECT row_number() OVER (ORDER BY customer_id, updated_at) AS customer_key,
           customer_id, first_name || ' ' || last_name AS full_name, email,
           country_code, segment,
           CASE WHEN row_number() OVER (PARTITION BY customer_id ORDER BY updated_at) = 1
                THEN TIMESTAMP '1900-01-01' ELSE updated_at END AS valid_from,
           lead(updated_at) OVER (PARTITION BY customer_id ORDER BY updated_at) AS valid_to
    FROM versions
    """)
    con.sql("""
    CREATE OR REPLACE TABLE fct_sales AS
    SELECT i.order_line_id, i.order_id, o.order_date, o.channel, o.status,
           coalesce(c.customer_key, -1) AS customer_key, p.product_key, p.category,
           i.quantity, i.net_amount,
           round(i.net_amount - i.quantity * p.unit_cost, 2) AS gross_profit
    FROM stg_order_items i
    JOIN stg_orders o ON o.order_id = i.order_id
    LEFT JOIN dim_product p ON p.product_id = i.product_id
    LEFT JOIN dim_customer c
      ON c.customer_id = o.customer_id
     AND o.order_ts >= c.valid_from
     AND o.order_ts <  coalesce(c.valid_to, TIMESTAMP '9999-12-31')
    WHERE i.is_valid
    """)


def main():
    con = duckdb.connect()
    build(con)
    raw_lines = con.execute(f"SELECT count(*) FROM read_csv_auto('{RAW}/order_items.csv')").fetchall()[0][0]
    stg_lines = con.execute("SELECT count(*) FROM stg_order_items").fetchall()[0][0]
    invalid = con.execute("SELECT count(*) FROM stg_order_items WHERE NOT is_valid").fetchall()[0][0]

    report = f"""# Sample pipeline output

_Generated by `scripts/local_preview.py` (DuckDB) from the CSVs in `data/raw/`.
The Snowflake SQL in `sql/` implements the same logic at scale._

## Data cleansing results

| Metric | Value |
|---|---|
| Raw order lines | {raw_lines} |
| After de-duplication | {stg_lines} |
| Duplicates removed | {raw_lines - stg_lines} |
| Invalid lines quarantined (qty <= 0) | {invalid} |
| Customer versions in SCD2 dimension | {con.execute("SELECT count(*) FROM dim_customer").fetchall()[0][0]} |
| Customers with history (>1 version) | {con.execute("SELECT count(*) FROM (SELECT customer_id FROM dim_customer GROUP BY 1 HAVING count(*) > 1)").fetchall()[0][0]} |
| Fact rows with unknown customer | {con.execute("SELECT count(*) FROM fct_sales WHERE customer_key = -1").fetchall()[0][0]} |

## Revenue by category (completed orders)

{md_table(con, '''
SELECT category, count(DISTINCT order_id) AS orders, sum(quantity) AS units,
       round(sum(net_amount), 2) AS net_revenue, round(sum(gross_profit), 2) AS gross_profit,
       round(100 * sum(gross_profit) / sum(net_amount), 1) AS margin_pct
FROM fct_sales WHERE status = 'COMPLETED'
GROUP BY 1 ORDER BY net_revenue DESC''')}

## Monthly revenue by channel

{md_table(con, '''
SELECT strftime(order_date, '%Y-%m') AS month, channel,
       count(DISTINCT order_id) AS orders, round(sum(net_amount), 2) AS net_revenue
FROM fct_sales WHERE status = 'COMPLETED'
GROUP BY 1, 2 ORDER BY 1, 2''')}

## SCD Type 2 example (customer with segment change)

{md_table(con, '''
SELECT customer_key, customer_id, full_name, segment, valid_from, valid_to,
       valid_to IS NULL AS is_current
FROM dim_customer
WHERE customer_id = (SELECT customer_id FROM dim_customer GROUP BY 1 HAVING count(*) > 1 ORDER BY 1 LIMIT 1)
ORDER BY valid_from''')}

## Top 10 customers by lifetime revenue

{md_table(con, '''
SELECT c.customer_id, any_value(c.full_name) AS full_name,
       count(DISTINCT f.order_id) AS orders, round(sum(f.net_amount), 2) AS lifetime_revenue
FROM fct_sales f JOIN dim_customer c ON c.customer_key = f.customer_key
WHERE f.status = 'COMPLETED'
GROUP BY 1 ORDER BY lifetime_revenue DESC LIMIT 10''')}
"""
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(report)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
